#!/usr/bin/env python3
"""Write the generated indexes in the reference docs from the code.

Each reference page carries one block between ``<!-- BEGIN GENERATED INDEX -->``
and ``<!-- END GENERATED INDEX -->``:

- docs/TOOLS.md: every MCP tool in the registry, grouped by operation family.
- docs/CLI_REFERENCE.md: every ``kino`` command and its help line.
- docs/PYTHON_CLIENT.md: every public ``Client`` method and its summary line.

Usage:
    python scripts/generate_reference_index.py           # rewrite the blocks
    python scripts/generate_reference_index.py --check   # exit 1 if any is stale
"""

from __future__ import annotations

import argparse
import asyncio
import inspect
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEGIN = "<!-- BEGIN GENERATED INDEX -->"
END = "<!-- END GENERATED INDEX -->"
NOTE = "<!-- Generated by scripts/generate_reference_index.py; edit the code, then rerun it. -->"


def _cell(text: str | None) -> str:
    line = (text or "").strip().splitlines()[0] if (text or "").strip() else ""
    return line.replace("|", "\\|").strip()


_TOOLS: dict = {}


def _all_tools() -> dict:
    if not _TOOLS:
        os.environ["KINOCUT_TOOLS"] = "all"
        from kinocut.tool_registry import configure_tool_surface

        configure_tool_surface()
        from kinocut.server_app import mcp

        _TOOLS.update({tool.name: tool for tool in asyncio.run(mcp.list_tools())})
    return _TOOLS


def tools_index() -> str:
    from kinocut import tool_families

    tools = _all_tools()
    lines = [
        f"{len(tools)} tools with `KINOCUT_TOOLS=all`, grouped by the family that dispatches them on the default surface."
    ]
    grouped: set[str] = set()
    for family, operations in tool_families.FAMILY_OPERATIONS.items():
        title = tool_families.FAMILY_TITLES.get(family, family)
        lines += ["", f"### `{family}`: {title} ({len(operations)})", "", "| Tool | Summary |", "| --- | --- |"]
        for name in sorted(operations):
            grouped.add(name)
            lines.append(f"| `{name}` | {_cell(tools[name].description)} |")
    rest = sorted(set(tools) - grouped)
    if rest:
        lines += ["", f"### Not in a family ({len(rest)})", "", "| Tool | Summary |", "| --- | --- |"]
        lines += [f"| `{name}` | {_cell(tools[name].description)} |" for name in rest]
    return "\n".join(lines)


def cli_index() -> str:
    from kinocut.cli.parser import build_parser

    parser = build_parser()
    action = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    helps = {choice.dest: choice.help for choice in action._choices_actions}
    names = sorted(action.choices)
    lines = [
        f"{len(names)} commands. Run `kino COMMAND --help` for flags.",
        "",
        "| Command | Summary |",
        "| --- | --- |",
    ]
    lines += [f"| `{name}` | {_cell(helps.get(name) or action.choices[name].description)} |" for name in names]
    return "\n".join(lines)


def client_index() -> str:
    from kinocut.client import Client

    tools = _all_tools()

    def summary(name: str) -> str:
        doc = _cell(inspect.getdoc(getattr(Client, name)))
        if doc:
            return doc
        # Undocumented methods borrow the summary of the MCP tool with the matching name.
        matches = sorted((n for n in tools if n == name or n.endswith("_" + name)), key=len)
        return f"See MCP `{matches[0]}`: {_cell(tools[matches[0]].description)}" if matches else ""

    names = sorted(m for m in dir(Client) if not m.startswith("_") and callable(getattr(Client, m)))
    lines = [f"{len(names)} public methods.", "", "| Method | Summary |", "| --- | --- |"]
    lines += [f"| `{name}()` | {summary(name)} |" for name in names]
    return "\n".join(lines)


TARGETS = {
    "docs/TOOLS.md": tools_index,
    "docs/CLI_REFERENCE.md": cli_index,
    "docs/PYTHON_CLIENT.md": client_index,
}


def render(text: str, body: str, path: str) -> str:
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{path}: missing {BEGIN} / {END} markers")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{BEGIN}\n{NOTE}\n\n{body}\n\n{END}{tail}"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if a generated block is stale")
    args = ap.parse_args()
    sys.path.insert(0, str(ROOT))
    stale = []
    for rel, build in TARGETS.items():
        path = ROOT / rel
        text = path.read_text(encoding="utf-8")
        new = render(text, build(), rel)
        if new != text:
            stale.append(rel)
            if not args.check:
                path.write_text(new, encoding="utf-8")
    if args.check and stale:
        print("stale generated index: " + ", ".join(stale) + "; run scripts/generate_reference_index.py")
        return 1
    print(("rewrote: " + ", ".join(stale)) if stale and not args.check else "up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
