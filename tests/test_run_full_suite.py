"""Keep the two-phase full-suite runner exhaustive and its serial list honest."""

from __future__ import annotations

import importlib.util
import os
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

from coverage import CoverageData
import pytest

from tests.conftest import PROCESS_TIMING_FILES

ROOT = Path(__file__).resolve().parents[1]


def _runner():
    spec = importlib.util.spec_from_file_location("run_full_suite", ROOT / "scripts" / "run_full_suite.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_every_process_timing_file_exists():
    missing = sorted(name for name in PROCESS_TIMING_FILES if not (ROOT / "tests" / name).is_file())
    assert not missing, f"stale PROCESS_TIMING_FILES entries: {missing}"


def _marker_expr(cmd: list[str]) -> str:
    return cmd[len(cmd) - 1 - cmd[::-1].index("-m") + 1]


def test_phases_partition_the_suite_on_the_marker():
    phases = dict(_runner()._phases("4", ["-k", "x"]))
    parallel, serial = phases["parallel"], phases["process-timing (serial)"]
    assert _marker_expr(parallel) == "not process_timing"
    assert _marker_expr(serial) == "process_timing"
    assert "-n" in parallel and "-n" not in serial
    for cmd in (parallel, serial):
        assert cmd[cmd.index("pytest") + 1] == "tests/"
        assert {"-x", "-k"} <= set(cmd)


def test_marker_in_passthrough_is_rejected():
    with pytest.raises(SystemExit) as exc:
        _runner().main(["--", "-m", "slow"])
    assert exc.value.code == 2


def test_empty_selection_in_every_phase_fails(monkeypatch):
    runner = _runner()
    monkeypatch.setattr(runner.subprocess, "call", lambda cmd: 5)
    assert runner.main([]) == 5
    calls = iter([5, 0])
    monkeypatch.setattr(runner.subprocess, "call", lambda cmd: next(calls))
    assert runner.main([]) == 0


def test_two_phase_ci_reports_and_selection(tmp_path):
    package = tmp_path / "example.py"
    package.write_text("def parallel():\n    return 1\n\ndef serial():\n    return 2\n")
    tests = tmp_path / "tests"
    tests.mkdir()
    (tmp_path / ".coveragerc").write_text("[report]\nfail_under = 100\n")
    (tests / "test_selection.py").write_text(
        "import pytest, example, os\n"
        "def test_parallel():\n"
        "    assert os.environ['PYTEST_XDIST_WORKER_COUNT'] == '2' and example.parallel() == 1\n"
        "@pytest.mark.process_timing\ndef test_serial():\n"
        "    assert not os.environ.get('PYTEST_XDIST_WORKER') and example.serial() == 2\n"
        "@pytest.mark.slow\ndef test_excluded_parallel(): assert False\n"
        "@pytest.mark.slow\n@pytest.mark.process_timing\ndef test_excluded_serial(): assert False\n"
    )
    env = {k: v for k, v in os.environ.items() if not k.startswith(("PYTEST_", "COV_", "COVERAGE_"))}
    result = subprocess.run(
        [
            sys.executable,
            str(ROOT / "scripts/run_full_suite.py"),
            "-m",
            "not slow",
            "--workers",
            "2",
            "--cov=example",
            "--cov-report=term",
            "--junitxml=results.xml",
        ],
        cwd=tmp_path,
        env=env,
        text=True,
        capture_output=True,
        timeout=120,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    report = ET.parse(tmp_path / "results.xml")  # noqa: S314 -- generated by this fixture's own subprocess
    assert sorted(case.get("name") for case in report.iter("testcase")) == ["test_parallel", "test_serial"]
    data = CoverageData(basename=str(tmp_path / ".coverage"))
    data.read()
    assert {2, 5} <= set(data.lines(str(package)) or [])
